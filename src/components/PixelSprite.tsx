// Animation state type
export type AnimationState = 'idle' | 'attack' | 'hit' | 'cast' | 'death';

interface PixelSpriteProps {
  family: string;
  element: Element;
  size?: number;
  animation?: AnimationState;
  showShadow?: boolean;
}

export function PixelSprite({ family, element, size = 48, animation = 'idle', showShadow = true }: PixelSpriteProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const palette = ELEMENT_PALETTES[element];
    const sprite = MONSTER_SPRITES[family] || MONSTER_SPRITES['Pixie']; // fallback

    const pixelSize = size / 16;

    // Clear
    ctx.clearRect(0, 0, size, size);

    // Animation transforms
    let offsetX = 0;
    let offsetY = 0;
    let scaleX = 1;
    let alpha = 1;

    if (animation === 'attack') {
      offsetX = Math.sin(Date.now() / 50) * 3;
    } else if (animation === 'hit') {
      offsetX = Math.sin(Date.now() / 30) * 2;
      alpha = 0.7 + Math.sin(Date.now() / 100) * 0.3;
    } else if (animation === 'cast') {
      offsetY = Math.sin(Date.now() / 80) * -2;
    } else if (animation === 'death') {
      alpha = 0.3;
      offsetY = 2;
    } else {
      // idle bounce
      offsetY = Math.sin(Date.now() / 500) * 1;
    }

    ctx.globalAlpha = alpha;
    ctx.save();
    ctx.translate(offsetX, offsetY);
    ctx.scale(scaleX, 1);

    const colorMap: Record<number, string> = {
      1: palette.outline,
      2: palette.primary,
      3: palette.secondary,
      4: palette.accent,
      5: '#FFFFFF', // eyes always white
    };

    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x++) {
        const val = sprite[y]?.[x] ?? 0;
        if (val === 0) continue;
        ctx.fillStyle = colorMap[val] || palette.primary;
        ctx.fillRect(
          Math.floor(x * pixelSize),
          Math.floor(y * pixelSize),
          Math.ceil(pixelSize),
          Math.ceil(pixelSize)
        );
      }
    }

    ctx.restore();
    ctx.globalAlpha = 1;

    // Shadow
    if (showShadow) {
      ctx.fillStyle = 'rgba(0,0,0,0.3)';
      ctx.beginPath();
      ctx.ellipse(size / 2, size - 2, size / 3, 3, 0, 0, Math.PI * 2);
      ctx.fill();
    }
  }, [family, element, size, animation]);

  // For idle animation, we need requestAnimationFrame
  useEffect(() => {
    if (animation === 'idle') {
      let frameId: number;
      const canvas = canvasRef.current;
      if (!canvas) return;
      const ctx = canvas.getContext('2d');
      if (!ctx) return;

      const palette = ELEMENT_PALETTES[element];
      const sprite = MONSTER_SPRITES[family] || MONSTER_SPRITES['Pixie'];
      const pixelSize = size / 16;

      const colorMap: Record<number, string> = {
        1: palette.outline,
        2: palette.primary,
        3: palette.secondary,
        4: palette.accent,
        5: '#FFFFFF',
      };

      const draw = () => {
        ctx.clearRect(0, 0, size, size);
        const offsetY = Math.sin(Date.now() / 500) * 1.5;

        ctx.save();
        ctx.translate(0, offsetY);

        for (let y = 0; y < 16; y++) {
          for (let x = 0; x < 16; x++) {
            const val = sprite[y]?.[x] ?? 0;
            if (val === 0) continue;
            ctx.fillStyle = colorMap[val] || palette.primary;
            ctx.fillRect(
              Math.floor(x * pixelSize),
              Math.floor(y * pixelSize),
              Math.ceil(pixelSize),
              Math.ceil(pixelSize)
            );
          }
        }
        ctx.restore();

        if (true) {
          ctx.fillStyle = 'rgba(0,0,0,0.3)';
          ctx.beginPath();
          ctx.ellipse(size / 2, size - 2, size / 3, 3, 0, 0, Math.PI * 2);
          ctx.fill();
        }

        frameId = requestAnimationFrame(draw);
      };

      draw();
      return () => cancelAnimationFrame(frameId);
    }
  }, [family, element, size, animation]);

  return (
    <canvas
      ref={canvasRef}
      width={size}
      height={size}
      style={{
        imageRendering: 'pixelated',
        width: size,
        height: size,
      }}
    />
  );
}

// Inline small sprite for lists (renders a static snapshot)
export function MiniSprite({ family, element, size = 24 }: { family: string; element: Element; size?: number }) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const palette = ELEMENT_PALETTES[element];
    const sprite = MONSTER_SPRITES[family] || MONSTER_SPRITES['Pixie'];
    const pixelSize = size / 16;

    ctx.clearRect(0, 0, size, size);

    const colorMap: Record<number, string> = {
      1: palette.outline,
      2: palette.primary,
      3: palette.secondary,
      4: palette.accent,
      5: '#FFFFFF',
    };

    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x++) {
        const val = sprite[y]?.[x] ?? 0;
        if (val === 0) continue;
        ctx.fillStyle = colorMap[val] || palette.primary;
        ctx.fillRect(
          Math.floor(x * pixelSize),
          Math.floor(y * pixelSize),
          Math.ceil(pixelSize),
          Math.ceil(pixelSize)
        );
      }
    }
  }, [family, element, size]);

  return (
    <canvas
      ref={canvasRef}
      width={size}
      height={size}
      style={{
        imageRendering: 'pixelated',
        width: size,
        height: size,
        verticalAlign: 'middle',
      }}
    />
  );
}

